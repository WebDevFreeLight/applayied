function Translate-ChineseInFile {
    param (
        [string]$FilePath
    )
    
    try {
        $content = Get-Content -Path $FilePath -Raw -Encoding UTF8
        if (-not $content) { return $false }
        
        $originalContent = $content
        
        # Sort translations by length (longest first) to avoid partial replacements
        $sortedTranslations = $translationMap.GetEnumerator() | Sort-Object { $_.Key.Length } -Descending
        
        foreach ($translation in $sortedTranslations) {
            $key = $translation.Key
            $value = $translation.Value
            
            # Escape special regex characters
            $escapedKey = [regex]::Escape($key)
            
            # Replace in various contexts
            # 1. In double quotes
            $content = $content -replace """$escapedKey""", """$value"""
            
            # 2. In XML comments (multiple patterns)
            $content = $content -replace "/// $escapedKey", "/// $value"
            $content = $content -replace "///$escapedKey", "/// $value"
            
            # 3. In regular comments
            $content = $content -replace "// $escapedKey", "// $value"
            $content = $content -replace "//$escapedKey", "// $value"
            
            # 4. In SugarColumn attributes
            $content = $content -replace "ColumnDescription = ""$escapedKey""", "ColumnDescription = ""$value"""
            
            # 5. In SugarTable attributes
            $content = $content -replace "\[SugarTable\(([^,]+), ""$escapedKey""\)", "[SugarTable(`$1, ""$value"")"
            
            # 6. In Log attributes
            $content = $content -replace "\[Log\(Title = ""$escapedKey""", "[Log(Title = ""$value"""
            
            # 7. In ExcelColumn attributes
            $content = $content -replace "\[ExcelColumn\(Name = ""$escapedKey""", "[ExcelColumn(Name = ""$value"""
            
            # 8. Special case for status descriptions like (0正常 1停用)
            if ($key -match '\d[^\s\)]+') {
                $content = $content -replace "\($escapedKey", "($value"
                $content = $content -replace "（$escapedKey", "($value"
            }
        }
        
        if ($content -ne $originalContent) {
            Set-Content -Path $FilePath -Value $content -Encoding UTF8 -NoNewline
            return $true
        }
        
        return $false
    }
    catch {
        Write-Host "Error processing ${FilePath}: $_" -ForegroundColor Red
        return $false
    }
}

# Main execution
Write-Host "Starting Chinese to English translation for all .cs files..." -ForegroundColor Cyan
Write-Host "This may take a few minutes depending on the number of files..." -ForegroundColor Yellow

$csFiles = Get-ChildItem -Path . -Filter "*.cs" -Recurse -File
$totalFiles = $csFiles.Count
$translatedFiles = 0
$processedFiles = 0

Write-Host "Found $totalFiles .cs files to process" -ForegroundColor Green

foreach ($file in $csFiles) {
    $processedFiles++
    $percentComplete = [math]::Round(($processedFiles / $totalFiles) * 100, 1)
    
    Write-Progress -Activity "Translating Chinese to English" `
                   -Status "Processing: $($file.Name)" `
                   -PercentComplete $percentComplete `
                   -CurrentOperation "$processedFiles of $totalFiles files"
    
    if (Translate-ChineseInFile -FilePath $file.FullName) {
        $translatedFiles++
        Write-Host "[$processedFiles/$totalFiles] ✓ $($file.FullName -replace [regex]::Escape($PWD.Path), '.')" -ForegroundColor Green
    }
}

Write-Progress -Activity "Translating Chinese to English" -Completed

Write-Host "`n==================== Translation Complete ====================" -ForegroundColor Cyan
Write-Host "Total files processed: $totalFiles" -ForegroundColor Yellow
Write-Host "Files modified: $translatedFiles" -ForegroundColor Green
Write-Host "Files unchanged: $($totalFiles - $translatedFiles)" -ForegroundColor Gray
Write-Host "==============================================================" -ForegroundColor Cyan

if ($translatedFiles -gt 0) {
    Write-Host "`nTranslation successful! Chinese text has been replaced with English." -ForegroundColor Green
} else {
    Write-Host "`nNo Chinese text found or all text already translated." -ForegroundColor Yellow
}