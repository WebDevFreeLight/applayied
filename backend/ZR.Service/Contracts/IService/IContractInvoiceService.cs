using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using ZR.Model;
using ZR.Model.Contracts.Dto;

namespace ZR.Service.Contracts.IService
{
    /// <summary>
    /// Contract Invoice Service Interface - واجهة خدمة فواتير العقود
    /// Orchestration service for creating AR Invoices from Contract Billing Schedules
    /// This service ONLY orchestrates - it does NOT duplicate Finance logic
    /// </summary>
    public interface IContractInvoiceService
    {
        #region Invoice Creation

        /// <summary>
        /// Create AR Invoice from a single billing schedule
        /// إنشاء فاتورة من جدول فوترة واحد
        /// </summary>
        /// <param name="request">Invoice creation request</param>
        /// <param name="userName">User creating the invoice</param>
        /// <returns>Result containing invoice details or error</returns>
        Task<CreateInvoiceFromScheduleResultDto> CreateInvoiceFromScheduleAsync(
            CreateInvoiceFromScheduleRequestDto request,
            string userName);

        /// <summary>
        /// Create AR Invoices from multiple billing schedules
        /// إنشاء فواتير من جداول فوترة متعددة
        /// </summary>
        /// <param name="request">Bulk invoice creation request</param>
        /// <param name="userName">User creating the invoices</param>
        /// <returns>Bulk result with success/failure details</returns>
        Task<BulkCreateInvoicesResultDto> BulkCreateInvoicesFromSchedulesAsync(
            BulkCreateInvoicesFromSchedulesRequestDto request,
            string userName);

        /// <summary>
        /// Auto-generate invoices for all due billing schedules
        /// إنشاء الفواتير تلقائياً لجميع الجداول المستحقة
        /// </summary>
        /// <param name="asOfDate">Date to check due schedules (defaults to today)</param>
        /// <param name="autoPost">Whether to auto-post created invoices</param>
        /// <param name="contractId">Optional: filter by contract</param>
        /// <param name="userName">User generating invoices</param>
        /// <returns>Bulk result with success/failure details</returns>
        Task<BulkCreateInvoicesResultDto> AutoGenerateDueInvoicesAsync(
            DateTime? asOfDate,
            bool autoPost,
            Guid? contractId,
            string userName);

        #endregion

        #region Validation

        /// <summary>
        /// Validate a billing schedule for invoice creation
        /// التحقق من جدول فوترة لإنشاء فاتورة
        /// </summary>
        /// <param name="scheduleId">Schedule to validate</param>
        /// <returns>Validation result with errors/warnings</returns>
        Task<ScheduleInvoiceValidationResultDto> ValidateScheduleForInvoicingAsync(Guid scheduleId);

        /// <summary>
        /// Validate multiple schedules for bulk invoicing
        /// التحقق من جداول متعددة للفوترة الجماعية
        /// </summary>
        /// <param name="scheduleIds">Schedules to validate</param>
        /// <returns>Dictionary of schedule ID to validation result</returns>
        Task<Dictionary<Guid, ScheduleInvoiceValidationResultDto>> ValidateSchedulesForInvoicingAsync(
            List<Guid> scheduleIds);

        #endregion

        #region Void/Cancel

        /// <summary>
        /// Void an invoice and optionally reopen the billing schedule
        /// إلغاء فاتورة وإعادة فتح جدول الفوترة اختيارياً
        /// </summary>
        /// <param name="request">Void request details</param>
        /// <param name="userName">User voiding the invoice</param>
        /// <returns>Number of affected records</returns>
        Task<int> VoidContractInvoiceAsync(VoidContractInvoiceRequestDto request, string userName);

        #endregion

        #region Query

        /// <summary>
        /// Get invoices by contract ID
        /// الحصول على الفواتير حسب معرف العقد
        /// </summary>
        /// <param name="contractId">Contract ID</param>
        /// <returns>List of contract invoices</returns>
        List<ContractInvoiceListDto> GetInvoicesByContractId(Guid contractId);

        /// <summary>
        /// Get paginated list of contract invoices
        /// الحصول على قائمة فواتير العقود مع الترقيم
        /// </summary>
        /// <param name="query">Query parameters</param>
        /// <param name="pager">Pager info</param>
        /// <returns>Paginated list of invoices</returns>
        PagedInfo<ContractInvoiceListDto> GetContractInvoices(ContractInvoiceQueryDto query, PagerInfo pager);

        #endregion
    }

    /// <summary>
    /// Schedule Invoice Validation Result DTO - نتيجة التحقق من الجدول للفوترة
    /// </summary>
    public class ScheduleInvoiceValidationResultDto
    {
        /// <summary>
        /// Is Valid - صالح للفوترة
        /// </summary>
        public bool IsValid { get; set; }

        /// <summary>
        /// Errors - الأخطاء (تمنع إنشاء الفاتورة)
        /// </summary>
        public List<string> Errors { get; set; } = new List<string>();

        /// <summary>
        /// Warnings - التحذيرات (لا تمنع إنشاء الفاتورة)
        /// </summary>
        public List<string> Warnings { get; set; } = new List<string>();
    }
}
