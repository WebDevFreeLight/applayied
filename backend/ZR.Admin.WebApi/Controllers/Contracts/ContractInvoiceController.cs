using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using System;
using System.Collections.Generic;
using System.Threading.Tasks;
using ZR.Admin.WebApi.Filters;
using ZR.Model;
using ZR.Model.Contracts.Dto;
using ZR.Service.Contracts.IService;

namespace ZR.Admin.WebApi.Controllers.Contracts
{
    /// <summary>
    /// Contract Invoice Controller - إدارة فواتير العقود
    /// API endpoints for creating AR Invoices from Contract Billing Schedules
    /// This controller ONLY orchestrates - Finance module handles all accounting logic
    /// </summary>
    [Authorize]
    [Route("erp/contracts/invoices")]
    [ApiController]
    public class ContractInvoiceController : BaseController
    {
        private readonly IContractInvoiceService _contractInvoiceService;

        public ContractInvoiceController(IContractInvoiceService contractInvoiceService)
        {
            _contractInvoiceService = contractInvoiceService;
        }

        #region Invoice Creation

        /// <summary>
        /// Create AR Invoice from a single billing schedule
        /// إنشاء فاتورة من جدول فوترة واحد
        /// </summary>
        /// <param name="request">Invoice creation request</param>
        /// <returns>Created invoice details</returns>
        [HttpPost("from-schedule")]
        [Log(Title = "Contract Invoice", BusinessType = BusinessType.INSERT)]
        public async Task<IActionResult> CreateFromSchedule([FromBody] CreateInvoiceFromScheduleRequestDto request)
        {
            if (!ModelState.IsValid)
            {
                return ToResponse(ResultCode.PARAM_ERROR);
            }

            try
            {
                var result = await _contractInvoiceService.CreateInvoiceFromScheduleAsync(
                    request,
                    HttpContext.GetName());

                if (result.Success)
                {
                    return SUCCESS(result);
                }
                else
                {
                    return ToResponse(ResultCode.FAIL, result.ErrorMessage);
                }
            }
            catch (Exception ex)
            {
                return ToResponse(ResultCode.FAIL, ex.Message);
            }
        }

        /// <summary>
        /// Create AR Invoices from multiple billing schedules
        /// إنشاء فواتير من جداول فوترة متعددة
        /// </summary>
        /// <param name="request">Bulk invoice creation request</param>
        /// <returns>Bulk creation results</returns>
        [HttpPost("bulk-create")]
        [Log(Title = "Contract Invoice Bulk", BusinessType = BusinessType.INSERT)]
        public async Task<IActionResult> BulkCreateFromSchedules([FromBody] BulkCreateInvoicesFromSchedulesRequestDto request)
        {
            if (!ModelState.IsValid)
            {
                return ToResponse(ResultCode.PARAM_ERROR);
            }

            try
            {
                var result = await _contractInvoiceService.BulkCreateInvoicesFromSchedulesAsync(
                    request,
                    HttpContext.GetName());

                return SUCCESS(result);
            }
            catch (Exception ex)
            {
                return ToResponse(ResultCode.FAIL, ex.Message);
            }
        }

        /// <summary>
        /// Auto-generate invoices for all due billing schedules
        /// إنشاء الفواتير تلقائياً لجميع الجداول المستحقة
        /// </summary>
        /// <param name="asOfDate">Optional: date to check due schedules (defaults to today)</param>
        /// <param name="autoPost">Whether to auto-post created invoices</param>
        /// <param name="contractId">Optional: filter by specific contract</param>
        /// <returns>Bulk creation results</returns>
        [HttpPost("auto-generate")]
        [Log(Title = "Contract Invoice Auto-Generate", BusinessType = BusinessType.INSERT)]
        public async Task<IActionResult> AutoGenerateDueInvoices(
            [FromQuery] DateTime? asOfDate,
            [FromQuery] bool autoPost = false,
            [FromQuery] Guid? contractId = null)
        {
            try
            {
                var result = await _contractInvoiceService.AutoGenerateDueInvoicesAsync(
                    asOfDate,
                    autoPost,
                    contractId,
                    HttpContext.GetName());

                return SUCCESS(result);
            }
            catch (Exception ex)
            {
                return ToResponse(ResultCode.FAIL, ex.Message);
            }
        }

        #endregion

        #region Validation

        /// <summary>
        /// Validate a billing schedule for invoice creation
        /// التحقق من جدول فوترة لإنشاء فاتورة
        /// </summary>
        /// <param name="scheduleId">Schedule ID to validate</param>
        /// <returns>Validation result with errors/warnings</returns>
        [HttpGet("validate/{scheduleId}")]
        public async Task<IActionResult> ValidateSchedule(Guid scheduleId)
        {
            try
            {
                var result = await _contractInvoiceService.ValidateScheduleForInvoicingAsync(scheduleId);
                return SUCCESS(result);
            }
            catch (Exception ex)
            {
                return ToResponse(ResultCode.FAIL, ex.Message);
            }
        }

        /// <summary>
        /// Validate multiple schedules for bulk invoicing
        /// التحقق من جداول متعددة للفوترة الجماعية
        /// </summary>
        /// <param name="scheduleIds">List of schedule IDs to validate</param>
        /// <returns>Dictionary of schedule ID to validation result</returns>
        [HttpPost("validate-bulk")]
        public async Task<IActionResult> ValidateSchedules([FromBody] List<Guid> scheduleIds)
        {
            if (scheduleIds == null || scheduleIds.Count == 0)
            {
                return ToResponse(ResultCode.PARAM_ERROR, "At least one schedule ID is required");
            }

            try
            {
                var result = await _contractInvoiceService.ValidateSchedulesForInvoicingAsync(scheduleIds);
                return SUCCESS(result);
            }
            catch (Exception ex)
            {
                return ToResponse(ResultCode.FAIL, ex.Message);
            }
        }

        #endregion

        #region Void/Cancel

        /// <summary>
        /// Void an invoice and optionally reopen the billing schedule
        /// إلغاء فاتورة وإعادة فتح جدول الفوترة اختيارياً
        /// </summary>
        /// <param name="request">Void request details</param>
        /// <returns>Result of void operation</returns>
        [HttpPost("void")]
        [Log(Title = "Contract Invoice Void", BusinessType = BusinessType.DELETE)]
        public async Task<IActionResult> VoidInvoice([FromBody] VoidContractInvoiceRequestDto request)
        {
            if (!ModelState.IsValid)
            {
                return ToResponse(ResultCode.PARAM_ERROR);
            }

            try
            {
                var result = await _contractInvoiceService.VoidContractInvoiceAsync(
                    request,
                    HttpContext.GetName());

                return SUCCESS(new { AffectedRecords = result });
            }
            catch (Exception ex)
            {
                return ToResponse(ResultCode.FAIL, ex.Message);
            }
        }

        #endregion

        #region Query

        /// <summary>
        /// Get invoices by contract ID
        /// الحصول على الفواتير حسب معرف العقد
        /// </summary>
        /// <param name="contractId">Contract ID</param>
        /// <returns>List of invoices for the contract</returns>
        [HttpGet("by-contract/{contractId}")]
        public IActionResult GetByContractId(Guid contractId)
        {
            try
            {
                var result = _contractInvoiceService.GetInvoicesByContractId(contractId);
                return SUCCESS(result);
            }
            catch (Exception ex)
            {
                return ToResponse(ResultCode.FAIL, ex.Message);
            }
        }

        /// <summary>
        /// Get paginated list of contract invoices
        /// الحصول على قائمة فواتير العقود مع الترقيم
        /// </summary>
        /// <param name="query">Query parameters</param>
        /// <param name="pager">Pager info</param>
        /// <returns>Paginated list of invoices</returns>
        [HttpGet("list")]
        public IActionResult GetList([FromQuery] ContractInvoiceQueryDto query, [FromQuery] PagerInfo pager)
        {
            try
            {
                var result = _contractInvoiceService.GetContractInvoices(query, pager);
                return SUCCESS(result);
            }
            catch (Exception ex)
            {
                return ToResponse(ResultCode.FAIL, ex.Message);
            }
        }

        #endregion
    }
}
