using Infrastructure.Converter;
using SqlSugar;
using Newtonsoft.Json;
using ZR.Model.System;

namespace ZR.Model.Operations
{
    /// <summary>
    /// Daily Report - اليومية
    /// </summary>
    [SugarTable("erp_daily_reports")]
    public class ErpDailyReport : SysBase
    {
        /// <summary>
        /// Report ID - معرف التقرير
        /// </summary>
        [SugarColumn(IsPrimaryKey = true, IsIdentity = false)]
        [JsonConverter(typeof(ValueToStringConverter))]
        public long ReportId { get; set; }

        /// <summary>
        /// Report Date gh - تاريخ التقرير
        /// </summary>
         public DateTime ReportDate { get; set; } 

        /// <summary>
        /// Total Sales - إجمالي المبيعات
        /// </summary>
        public decimal TotalSales { get; set; }

        /// <summary>
        /// Total Returns - إجمالي المرتجعات
        /// </summary>
        public decimal TotalReturns { get; set; }

        /// <summary>
        /// Net Sales - صافي المبيعات
        /// </summary>
        public decimal NetSales { get; set; }

        /// <summary>
        /// Total Subscriptions - إجمالي الإشتراكات
        /// </summary>
        public decimal TotalSubscriptions { get; set; }

        /// <summary>
        /// New Subscriptions Count - عدد الإشتراكات الجديدة
        /// </summary>
        public int NewSubscriptionsCount { get; set; }

        /// <summary>
        /// Renewed Subscriptions Count - عدد التجديدات
        /// </summary>
        public int RenewedSubscriptionsCount { get; set; }

        /// <summary>
        /// Total Purchases - إجمالي المشتريات
        /// </summary>
        public decimal TotalPurchases { get; set; }

        /// <summary>
        /// Total Expenses - إجمالي المصروفات
        /// </summary>
        public decimal TotalExpenses { get; set; }

        /// <summary>
        /// Total Receipts - إجمالي المقبوضات
        /// </summary>
        public decimal TotalReceipts { get; set; }

        /// <summary>
        /// Total Payments - إجمالي المدفوعات
        /// </summary>
        public decimal TotalPayments { get; set; }

        /// <summary>
        /// Cash Sales - مبيعات نقدية
        /// </summary>
        public decimal CashSales { get; set; }

        /// <summary>
        /// Card Sales - مبيعات بطاقات
        /// </summary>
        public decimal CardSales { get; set; }

        /// <summary>
        /// Transfer Sales - مبيعات تحويل
        /// </summary>
        public decimal TransferSales { get; set; }

        /// <summary>
        /// Net Cash Flow - صافي التدفق النقدي
        /// </summary>
        public decimal NetCashFlow { get; set; }

        /// <summary>
        /// Total Visits - إجمالي الزيارات
        /// </summary>
        public int TotalVisits { get; set; }

        /// <summary>
        /// New Members Count - عدد الأعضاء الجدد
        /// </summary>
        public int NewMembersCount { get; set; }

        /// <summary>
        /// Total Bookings - إجمالي الحجوزات
        /// </summary>
        public int TotalBookings { get; set; }

        /// <summary>
        /// Completed Bookings - الحجوزات المكتملة
        /// </summary>
        public int CompletedBookings { get; set; }

        /// <summary>
        /// Cancelled Bookings - الحجوزات الملغاة
        /// </summary>
        public int CancelledBookings { get; set; }

        /// <summary>
        /// Invoices Count - عدد الفواتير
        /// </summary>
        public int InvoicesCount { get; set; }

        /// <summary>
        /// Returns Count - عدد المرتجعات
        /// </summary>
        public int ReturnsCount { get; set; }

        /// <summary>
        /// Top Products - أفضل المنتجات (JSON)
        /// </summary>
        public string TopProducts { get; set; }

        /// <summary>
        /// Top Services - أفضل الخدمات (JSON)
        /// </summary>
        public string TopServices { get; set; }

        /// <summary>
        /// Top Packages - أفضل الباقات (JSON)
        /// </summary>
        public string TopPackages { get; set; }

        /// <summary>
        /// Sales By Employee - مبيعات حسب الموظف (JSON)
        /// </summary>
        public string SalesByEmployee { get; set; }

        /// <summary>
        /// Sales By Category - مبيعات حسب الفئة (JSON)
        /// </summary>
        public string SalesByCategory { get; set; }

        /// <summary>
        /// Is Auto Generated - مولد آلياً
        /// </summary>
        public bool IsAutoGenerated { get; set; } = true;

        /// <summary>
        /// Is Closed - مغلق
        /// </summary>
        public bool IsClosed { get; set; }

        /// <summary>
        /// Closed By - أغلق بواسطة
        /// </summary>
        public string ClosedBy { get; set; }

        /// <summary>
        /// Closed At - وقت الإغلاق
        /// </summary>
        public DateTime? ClosedAt { get; set; }

        /// <summary>
        /// Notes - ملاحظات
        /// </summary>
        public string Notes { get; set; }
    }
}

