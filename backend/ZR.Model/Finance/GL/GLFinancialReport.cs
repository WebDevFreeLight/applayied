using System;
using SqlSugar;
using ZR.Model.Finance.Enums;
using ZR.Model.System;

namespace ZR.Model.Finance.GL
{
    /// <summary>
    /// GL Financial Report - التقرير المالي
    /// </summary>
    [SugarTable("gl_financial_report")]
    public class GLFinancialReport : SysBase
    {
        /// <summary>
        /// Report ID - معرف التقرير
        /// </summary>
        [SugarColumn(IsPrimaryKey = true, IsIdentity = false, ColumnName = "id")]
        public Guid Id { get; set; }

        /// <summary>
        /// Report Type - نوع التقرير
        /// </summary>
        [SugarColumn(ColumnName = "report_type")]
        public ReportType ReportType { get; set; }

        /// <summary>
        /// Report Number - رقم التقرير
        /// </summary>
        [SugarColumn(Length = 50, ColumnName = "report_number")]
        public string ReportNumber { get; set; }

        /// <summary>
        /// Period Start Date - تاريخ بداية الفترة
        /// </summary>
        [SugarColumn(ColumnName = "period_start_date")]
        public DateTime PeriodStartDate { get; set; }

        /// <summary>
        /// Period End Date - تاريخ نهاية الفترة
        /// </summary>
        [SugarColumn(ColumnName = "period_end_date")]
        public DateTime PeriodEndDate { get; set; }

        /// <summary>
        /// Fiscal Year - السنة المالية
        /// </summary>
        [SugarColumn(ColumnName = "fiscal_year")]
        public int FiscalYear { get; set; }

        /// <summary>
        /// Description (Arabic) - الوصف بالعربي
        /// </summary>
        [SugarColumn(Length = 500, IsNullable = true, ColumnName = "description_ar")]
        public string DescriptionAr { get; set; }

        /// <summary>
        /// Description (English) - الوصف بالإنجليزي
        /// </summary>
        [SugarColumn(Length = 500, IsNullable = true, ColumnName = "description_en")]
        public string DescriptionEn { get; set; }

        /// <summary>
        /// Report Data (JSON) - بيانات التقرير
        /// </summary>
        [SugarColumn(ColumnDataType = "text", IsNullable = true, ColumnName = "report_data")]
        public string ReportData { get; set; }

        /// <summary>
        /// Total Debit - إجمالي المدين
        /// </summary>
        [SugarColumn(ColumnName = "total_debit", DecimalDigits = 4)]
        public decimal TotalDebit { get; set; }

        /// <summary>
        /// Total Credit - إجمالي الدائن
        /// </summary>
        [SugarColumn(ColumnName = "total_credit", DecimalDigits = 4)]
        public decimal TotalCredit { get; set; }

        /// <summary>
        /// Currency - العملة
        /// </summary>
        [SugarColumn(Length = 10, ColumnName = "currency")]
        public string Currency { get; set; } = "SAR";

        /// <summary>
        /// Generated At - تاريخ الإنشاء
        /// </summary>
        [SugarColumn(ColumnName = "generated_at")]
        public DateTime GeneratedAt { get; set; } = DateTime.Now;

        /// <summary>
        /// Generated By - أنشئ بواسطة
        /// </summary>
        [SugarColumn(IsNullable = true, ColumnName = "generated_by")]
        public Guid? GeneratedBy { get; set; }
    }
}

